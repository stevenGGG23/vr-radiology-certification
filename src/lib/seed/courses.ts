function mod(code: string, index: number, title: string, lessons: LessonSpec[]): Module {
  return {
    id: `${code}-m${index}`,
    title,
    lessons: lessons.map(([t, min, preview], i): Lesson => ({
      id: `${code}-m${index}-l${i + 1}`,
      title: t,
      durationMin: min,
      videoUrl: SAMPLE_VIDEOS[t] ?? "",
      preview: Boolean(preview),
      summary: "",
      resources: [],
    })),
  };
}

function q(prompt: string, choices: string[], answerIndex: number, explanation: string): Omit<Question, "id"> {
  return { prompt, choices, answerIndex, explanation };
}

function exam(code: string, questions: Omit<Question, "id">[], timeLimitMin = 30): ExamConfig {
  return {
    passingScore: 80,
    maxAttempts: 2,
    timeLimitMin,
    questions: questions.map((x, i) => ({ ...x, id: `${code}-q${i + 1}` })),
  };
}

